function formatBadgeCount(count: number): string {
  if (count > 99) return "99+";
  return String(count);
}

export function Sidebar() {
  const pathname = usePathname();
  const { count } = useDueFollowUpCount();

  return (
    <aside className="fixed left-0 top-0 bottom-0 w-56 bg-bg-elevated border-r border-border flex flex-col z-30">
      <div className="px-5 py-6 border-b border-border">
        <h1 className="font-heading text-lg font-bold text-primary tracking-tight">
          LeadRadar
        </h1>
        <p className="text-xs text-muted mt-0.5">数字包装商机雷达</p>
      </div>

      <nav className="flex-1 px-3 py-4 space-y-1">
        {NAV_ITEMS.map((item) => {
          const isActive =
            item.href === "/"
              ? pathname === "/"
              : pathname.startsWith(item.href);
          const showBadge = item.showBadge && count > 0;
          return (
            <Link
              key={item.href}
              href={item.href as never}
              className={cn(
                "flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm transition-colors duration-150",
                isActive
                  ? "bg-primary/[0.06] text-primary font-medium"
                  : "text-muted hover:text-foreground hover:bg-bg-muted"
              )}
            >
              {item.icon}
              <span className="flex-1">{item.label}</span>
              {showBadge && (
                <span
                  className="ml-auto"
                  title={`${count} 条到期跟进`}
                >
                  <Badge className="bg-danger text-white">
                    {formatBadgeCount(count)}
                  </Badge>
                </span>
              )}
            </Link>
          );
        })}
      </nav>

      <div className="px-5 py-4 border-t border-border space-y-3">
        <ThemeToggle />
        <p className="text-xs text-muted">v0.1.0 MVP</p>
      </div>
    </aside>
  );
}
